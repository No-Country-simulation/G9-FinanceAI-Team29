export function ConsoleBanner() {
  const { pathname } = useLocation();
  const lastPrintedPath = useRef<string | null>(null);

  useEffect(() => {
    // Evita la impresión duplicada que provoca StrictMode durante el desarrollo.
    if (lastPrintedPath.current === pathname) return;

    lastPrintedPath.current = pathname;

    // Se difiere para que los logs propios de la sección aparezcan primero.
    const timeoutId = window.setTimeout(() => {
      console.log(
        `%c${DEV_BANNER}`,
        "color: #12b76a; font-family: monospace; font-weight: bold; line-height: 1.15;",
      );
    }, 1500);

    return () => window.clearTimeout(timeoutId);
  }, [pathname]);

  return null;
}
